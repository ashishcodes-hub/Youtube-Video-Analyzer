
from fpdf import FPDF
import re



def safe_multi_cell(pdf, text, height=7):
    """Render text using manually wrapped FPDF cells."""

    text = str(text)
    max_width = pdf.w - pdf.l_margin - pdf.r_margin

    # Small safety margin
    max_width -= 2

    words = text.split()
    current_line = ""

    for word in words:

        # Break extremely long words character by character
        chunks = []
        chunk = ""

        for char in word:
            if pdf.get_string_width(chunk + char) <= max_width:
                chunk += char
            else:
                if chunk:
                    chunks.append(chunk)
                chunk = char

        if chunk:
            chunks.append(chunk)

        for part in chunks:

            test_line = (
                current_line + " " + part
                if current_line else part
            )

            if pdf.get_string_width(test_line) <= max_width:
                current_line = test_line
            else:
                if current_line:
                    pdf.cell(
                        max_width,
                        height,
                        current_line,
                        new_x="LMARGIN",
                        new_y="NEXT"
                    )

                current_line = part

    if current_line:
        pdf.cell(
            max_width,
            height,
            current_line,
            new_x="LMARGIN",
            new_y="NEXT"
        )



def create_summary_pdf(
    summary: str,
    video_title: str = "YouTube Video Analysis"
) -> bytes:

    pdf = FPDF(format="A4")
    pdf.set_margins(15, 15, 15)
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    # PDF Title
    pdf.set_font("Helvetica", "B", 18)

    title = str(video_title or "YouTube Video Analysis")
    title = title.encode("latin-1", "replace").decode("latin-1")

    safe_multi_cell(pdf, title, 10)
    pdf.ln(5)

    # Section heading
    pdf.set_font("Helvetica", "B", 14)
    safe_multi_cell(pdf, "Video Analysis Summary", 10)
    pdf.ln(3)

    # Convert Markdown into readable plain text
    text = str(summary or "")

    # Remove code block markers
    text = re.sub(r"```[\w-]*", "", text)

    # Remove Markdown images and links
    text = re.sub(r"!\[([^\]]*)\]\([^)]+\)", r"\1", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)

    # Remove Markdown headings and formatting
    text = re.sub(r"(?m)^#{1,6}\s*", "", text)
    text = re.sub(r"\*\*(.*?)\*\*", r"\1", text)
    text = re.sub(r"(?<!\*)\*([^*]+)\*(?!\*)", r"\1", text)
    text = re.sub(r"(?m)^\s*[-*]\s+", "- ", text)
    text = re.sub(r"(?m)^\s*\d+\.\s+", "- ", text)

    # Remove unsupported characters for built-in Helvetica
    text = text.encode("latin-1", "replace").decode("latin-1")

    # Summary content
    pdf.set_font("Helvetica", size=11)

    for line in text.splitlines():
        line = line.strip()

        if not line:
            pdf.ln(3)
            continue

        # IMPORTANT: use safe_multi_cell, not pdf.multi_cell
        safe_multi_cell(pdf, line, 7)

    # Footer
    pdf.ln(8)
    pdf.set_font("Helvetica", "I", 9)
    safe_multi_cell(pdf, "Generated by YouTube AI Analyzer", 8)

    return bytes(pdf.output())
